"""Regenerate evals/email/schema.sql from the live column definitions. READ-ONLY.

    python -m evals.email.gen_schema          (needs DB_* in the environment)

Columns, types, defaults and NOT NULL are copied; identity columns stay identity; constraints,
indexes and triggers are deliberately left out so a golden case can seed duplicate or orphan rows.
"""

from __future__ import annotations

import os
import sys
from pathlib import Path

TABLES = ["bp_policy", "bp_prompt", "supplier_response", "bp_supplier", "workflow_email_tracking", "bp_approval"]
HEADER = """-- GENERATED from the live column definitions of the tables below (read-only introspection).
-- Columns, types, defaults, NOT NULL and identity are faithful; constraints, indexes and triggers are
-- DELIBERATELY omitted so a golden case can seed the duplicate / orphan rows the code must still cope with.
-- Regenerate with: python -m evals.email.gen_schema

CREATE SCHEMA IF NOT EXISTS proc;
"""


def column_sql(row) -> str:
    name, dt, udt, ml, np_, ns, nullable, default, identity, generation = row
    if identity == "YES":
        # faithful: ALWAYS refuses an explicit value, BY DEFAULT accepts one, and the code must cope with the real kind
        return f"    {name} {'bigint' if dt == 'bigint' else 'integer'} GENERATED {generation} AS IDENTITY"
    if default and default.startswith("nextval"):
        return f"    {name} {'bigint' if dt == 'bigint' else 'integer'} GENERATED BY DEFAULT AS IDENTITY"
    if dt == "character varying":
        typ = f"varchar({ml})" if ml else "varchar"
    elif dt == "character":
        typ = f"char({ml})"
    elif dt == "numeric":
        typ = f"numeric({np_},{ns})" if np_ else "numeric"
    elif dt == "ARRAY":
        typ = udt.lstrip("_") + "[]"
    elif dt == "USER-DEFINED":
        typ = "text"
    else:
        typ = dt
    line = f"    {name} {typ}"
    if default is not None:
        line += f" DEFAULT {default}"
    if nullable == "NO":
        line += " NOT NULL"
    return line


def generate(conn) -> str:
    cur = conn.cursor()
    out = [HEADER]
    for t in TABLES:
        cur.execute(
            """SELECT column_name, data_type, udt_name, character_maximum_length, numeric_precision, numeric_scale,
                      is_nullable, column_default, is_identity, identity_generation
               FROM information_schema.columns WHERE table_schema = 'proc' AND table_name = %s
               ORDER BY ordinal_position""", (t,))
        cols = [column_sql(r) for r in cur.fetchall()]
        if not cols:
            raise SystemExit(f"proc.{t} not found")
        out.append(f"CREATE TABLE proc.{t} (\n" + ",\n".join(cols) + "\n);\n")
    return "\n".join(out)


if __name__ == "__main__":
    import psycopg2

    conn = psycopg2.connect(host=os.environ["DB_HOST"], dbname=os.environ["DB_NAME"], user=os.environ["DB_USER"],
                            password=os.environ["DB_PASSWORD"], port=os.environ.get("DB_PORT", 5432), connect_timeout=8)
    conn.set_session(readonly=True)
    Path(__file__).with_name("schema.sql").write_text(generate(conn))
    print("wrote", Path(__file__).with_name("schema.sql"), file=sys.stderr)
