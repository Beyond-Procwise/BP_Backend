"""The prompt registry is tested against a real, THROWAWAY PostgreSQL.

Its guarantees are database triggers (a saved version cannot be changed, the
pointer history is append-only), so the in-memory stand-in cannot test them.
And because those triggers refuse DELETE, a test can never clean up after
itself: pointing this at a shared database would leave rows there for good.
So it takes its own switch on top of the usual one:

    docker run -d --rm -e POSTGRES_PASSWORD=pe -e POSTGRES_DB=pe \
        -p 127.0.0.1:55439:5432 postgres:15
    PROCWISE_TEST_LIVE_DB=1 PROMPT_ENGINE_THROWAWAY_DB=1 \
        PGHOST=127.0.0.1 PGPORT=55439 PGUSER=postgres PGPASSWORD=pe PGDATABASE=pe \
        pytest tests/prompt_engine
"""
from __future__ import annotations

import os
import sys
import uuid
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[2]
sys.path.append(str(ROOT))
sys.path.append(str(ROOT / "src"))

_ON = ("1", "true", "yes", "on")


def _throwaway() -> bool:
    return (os.environ.get("PROCWISE_TEST_LIVE_DB", "").lower() in _ON
            and os.environ.get("PROMPT_ENGINE_THROWAWAY_DB", "").lower() in _ON)


LEGACY_TABLE = """
CREATE SCHEMA IF NOT EXISTS proc;
CREATE TABLE IF NOT EXISTS proc.bp_prompt (
    prompt_id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prompt_name          TEXT,
    prompt_type          TEXT,
    prompt_linked_agents TEXT,
    prompts_desc         JSONB,
    prompts_status       SMALLINT DEFAULT 1,
    version              INTEGER DEFAULT 1,
    created_date         TIMESTAMPTZ DEFAULT now(),
    created_by           TEXT,
    last_modified_date   TIMESTAMPTZ DEFAULT now(),
    last_modified_by     TEXT
);
"""


@pytest.fixture(scope="session")
def db():
    if not _throwaway():
        pytest.skip("needs a THROWAWAY PostgreSQL "
                    "(PROCWISE_TEST_LIVE_DB=1 and PROMPT_ENGINE_THROWAWAY_DB=1)")
    from services.db import get_conn

    with get_conn() as conn:
        cur = conn.cursor()
        cur.execute(LEGACY_TABLE)
        cur.execute((ROOT / "deploy/sql/2026-10-13_bp_prompt_registry.sql").read_text())
        cur.execute((ROOT / "deploy/sql/2026-10-13_bp_prompt_render.sql").read_text())
        cur.close()
    return get_conn


@pytest.fixture()
def key(db):
    return f"test_{uuid.uuid4().hex[:12]}"
