"""Write the tenant-isolation migration files (backlog 1.19, decision D-37) from classification.py.

    python scripts/tenancy/generate_migrations.py          # (re)writes deploy/sql/tenancy/*.sql
    python scripts/tenancy/generate_migrations.py --check  # exits 1 if the files on disk are stale

DRAFTS FOR REVIEW. Nothing here is applied by this script; it only writes files.
"""
from __future__ import annotations

import hashlib
import os
import sys
from typing import Dict, Iterable, List

sys.path.insert(0, os.path.dirname(__file__))
from classification import OWNED, REVIEW, SHARED  # noqa: E402

OUT = os.path.join(os.path.dirname(__file__), "..", "..", "deploy", "sql", "tenancy")
DATE = "2026-10-21"
LABEL = "default"   # D-37 Q1: every existing row belongs to this tenant label
UNBATCHED_BIG = {"bp_triage_result"}   # 4.6M rows; its backfill (if any NULLs) is batched


def ident(prefix: str, table: str, suffix: str) -> str:
    """A Postgres identifier of at most 63 characters, stable and unique per table."""
    name = f"{prefix}_{table}_{suffix}"
    if len(name) <= 63:
        return name
    tag = hashlib.sha1(table.encode()).hexdigest()[:8]
    return f"{prefix}_{table[:63 - len(prefix) - len(suffix) - 12]}_{tag}_{suffix}"


def owned() -> List[str]:
    return sorted(OWNED)


def check_classification(tables: Iterable[str]) -> None:
    """Refuse unless every table is in exactly one group."""
    tables = set(tables)
    groups = {"OWNED": OWNED, "SHARED": SHARED, "REVIEW": REVIEW}
    for a in groups:
        for b in groups:
            if a < b and groups[a] & groups[b]:
                raise SystemExit(f"in both {a} and {b}: {sorted(groups[a] & groups[b])}")
    known = OWNED | SHARED | REVIEW
    if tables - known:
        raise SystemExit(f"tables with no isolation decision (add to classification.py): {sorted(tables - known)}")
    if known - tables:
        raise SystemExit(f"classified but not in the table list (renamed or dropped?): {sorted(known - tables)}")


HEADER = """-- DRAFT FOR REVIEW. NOT APPLIED. Generated by scripts/tenancy/generate_migrations.py -- do not edit by hand.
-- Backlog 1.19, decision D-37: existing data belongs to tenant label '{label}'; row-level security is the
-- second wall; BP staff get read-only, logged support access.
-- Part {part}: {title}
{notes}
"""


def header(part: int, title: str, notes: str) -> str:
    return HEADER.format(label=LABEL, part=part, title=title, notes=notes.strip())


def p1_add_label() -> str:
    out = [header(1, "add the tenant label to every customer-owned table", f"""
-- Safe on a live database: ADD COLUMN with a constant DEFAULT is metadata-only in PostgreSQL 16, so it
-- labels every existing row '{LABEL}' instantly without rewriting the table. The DEFAULT is dropped
-- straight away (existing rows keep their label), so a future insert that forgets the label gets NULL
-- and is caught, instead of silently landing in '{LABEL}'.
-- Each table is its own short transaction with a lock timeout: if a table is busy the statement fails
-- and the file can be re-run (every statement is idempotent).
-- Tables that already carry tenant_id (20) keep it; part 2 relabels any NULL rows.
-- Reversible: 1_add_label_rollback.sql drops the column ONLY on tables this file added it to.""")]
    labelled = _already_labelled()
    for t in owned():
        if t in labelled:
            out.append(f"-- proc.{t}: already has tenant_id; its default (if any) is left alone here -- part 6 replaces it.\n")
            continue
        out.append(f"""BEGIN;
SET LOCAL lock_timeout = '3s';
ALTER TABLE proc.{t} ADD COLUMN IF NOT EXISTS tenant_id text DEFAULT '{LABEL}';
ALTER TABLE proc.{t} ALTER COLUMN tenant_id DROP DEFAULT;
COMMIT;
""")
    return "\n".join(out)


def p2_backfill() -> str:
    out = [header(2, "relabel any row that still has no label", f"""
-- Needed for the 20 tables that already had a tenant_id column (some rows are NULL) and for rows inserted
-- between part 1 and the application change. Batched so no long lock is held; re-run until it reports 0.
-- Rows are never guessed: single-tenant today, so every NULL becomes '{LABEL}' (D-37 Q1).
-- Also builds the per-table index CONCURRENTLY (cannot run inside a transaction, so none is opened here).""")]
    out.append(f"""CREATE OR REPLACE PROCEDURE pg_temp.bp_relabel(tbl regclass, batch int DEFAULT 20000)
LANGUAGE plpgsql AS $$
DECLARE n int;
BEGIN
  LOOP
    EXECUTE format('UPDATE %s SET tenant_id = %L WHERE ctid IN (SELECT ctid FROM %s WHERE tenant_id IS NULL LIMIT %s)',
                   tbl, '{LABEL}', tbl, batch);
    GET DIAGNOSTICS n = ROW_COUNT;
    EXIT WHEN n = 0;
    COMMIT;
  END LOOP;
END $$;
""")
    for t in owned():
        out.append(f"CALL pg_temp.bp_relabel('proc.{t}');")
    out.append("")
    for t in owned():
        out.append(f"CREATE INDEX CONCURRENTLY IF NOT EXISTS {ident('ix_bp', t, 'tenant')} ON proc.{t} (tenant_id);")
    out.append("")
    return "\n".join(out)


def p3_not_null() -> str:
    out = [header(3, "make the label mandatory", """
-- APPLY ONLY AFTER the gateway and the Python services write tenant_id on every insert (step 3 of the
-- design) and `SELECT count(*) ... WHERE tenant_id IS NULL` is 0 on every table (part 2 re-run).
-- Uses a validated CHECK first so SET NOT NULL does not need a second full scan or a long lock.
-- Reversible: 3_not_null_rollback.sql.""")]
    for t in owned():
        ck = ident("ck", t, "tenant_nn")
        out.append(f"""BEGIN;
SET LOCAL lock_timeout = '3s';
ALTER TABLE proc.{t} ADD CONSTRAINT {ck} CHECK (tenant_id IS NOT NULL) NOT VALID;
COMMIT;
ALTER TABLE proc.{t} VALIDATE CONSTRAINT {ck};
BEGIN;
SET LOCAL lock_timeout = '3s';
ALTER TABLE proc.{t} ALTER COLUMN tenant_id SET NOT NULL;
ALTER TABLE proc.{t} DROP CONSTRAINT {ck};
COMMIT;
""")
    return "\n".join(out)


def p6_stamp() -> str:
    withdefault = [t for t in _read_lines(_snap("proc_tables_label_default_2026-10-21.txt"))]
    out = [header(6, "stamp the tenant on every new row", f"""
-- APPLY AFTER part 1 and AFTER the application that sets app.tenant_id is running (tenant_context);
-- order: 1 -> 6 -> 2 -> [app] -> 3 -> 5 -> 4.
-- A BEFORE INSERT trigger fills tenant_id from the connection's app.tenant_id when the insert did not
-- name one, so ~200 INSERT statements in the code do not each have to. Rules:
--   * an insert that names a tenant keeps it (a platform job may name one; row-level security, part 4,
--     still refuses a name that is not the caller's);
--   * an insert that names none and has no tenant on the connection stays NULL: part 2 relabels it
--     until part 3, and part 3's NOT NULL refuses it after -- it is never guessed into '{LABEL}'.
-- {len(withdefault)} owned tables already carried tenant_id NOT NULL DEFAULT '{LABEL}'. That default would
-- fill the label BEFORE this trigger ran, so for those tables the default is dropped in the same
-- transaction that creates the trigger (no moment with neither).
-- Reversible: 6_stamp_on_insert_rollback.sql (puts the default back).""")]
    out.append("""CREATE OR REPLACE FUNCTION proc.bp_stamp_tenant() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.tenant_id IS NULL THEN
    NEW.tenant_id := nullif(current_setting('app.tenant_id', true), '');
  END IF;
  RETURN NEW;
END $$;
""")
    for t in owned():
        drop = f"ALTER TABLE proc.{t} ALTER COLUMN tenant_id DROP DEFAULT;\n" if t in withdefault else ""
        out.append(f"""BEGIN;
SET LOCAL lock_timeout = '3s';
DROP TRIGGER IF EXISTS tr_bp_stamp_tenant ON proc.{t};
CREATE TRIGGER tr_bp_stamp_tenant BEFORE INSERT ON proc.{t}
  FOR EACH ROW EXECUTE FUNCTION proc.bp_stamp_tenant();
{drop}COMMIT;
""")
    return "\n".join(out)


def p4_rls(views: List[str]) -> str:
    out = [header(4, "row-level security: the second wall", """
-- APPLY ONLY AFTER part 3 AND after the application sets the tenant on every connection:
--     SELECT set_config('app.tenant_id', '<tenant from the VERIFIED token>', false)
-- A connection that sets nothing sees ZERO rows (fails closed). Background jobs that legitimately span
-- tenants must say so explicitly:  SELECT set_config('app.system', 'on', false)  -- never from a request.
-- FORCE is required: the application connects as, and SET ROLEs to, the table owner, who would
-- otherwise bypass every policy.
-- BP staff (Q3): role procwise_readonly may SELECT across tenants, and only while a reason is on record
-- (see part 5). It has no INSERT/UPDATE/DELETE policy, so it cannot write.
-- Views are switched to the caller's rights (PostgreSQL 15+) so they cannot read around the policy.
-- Reversible: 4_row_level_security_rollback.sql.""")]
    cond = ("tenant_id = current_setting('app.tenant_id', true)\n"
            "       OR current_setting('app.system', true) = 'on'")
    for t in owned():
        out.append(f"""ALTER TABLE proc.{t} ENABLE ROW LEVEL SECURITY;
ALTER TABLE proc.{t} FORCE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS bp_tenant_isolation ON proc.{t};
CREATE POLICY bp_tenant_isolation ON proc.{t}
  USING ({cond})
  WITH CHECK ({cond});
DROP POLICY IF EXISTS bp_support_read ON proc.{t};
CREATE POLICY bp_support_read ON proc.{t} FOR SELECT TO procwise_readonly
  USING (nullif(current_setting('app.support_reason', true), '') IS NOT NULL);
""")
    for v in views:
        out.append(f"ALTER VIEW proc.{v} SET (security_invoker = true);")
    out.append("")
    return "\n".join(out)


def p5_support_log() -> str:
    return header(5, "logged, read-only support access (Q3)", """
-- BP staff open a support window with a reason; it is recorded, and only then can procwise_readonly read
-- another tenant's rows (the bp_support_read policy in part 4 requires app.support_reason to be set).
-- Append-only: no UPDATE or DELETE for anyone but the owner role's break-glass login.
-- Apply before part 4.""") + """
BEGIN;
CREATE TABLE IF NOT EXISTS proc.bp_support_access_log (
    log_id      bigserial PRIMARY KEY,
    opened_by   text        NOT NULL,
    reason      text        NOT NULL CHECK (length(btrim(reason)) >= 10),
    tenant_id   text,
    opened_at   timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_bp_support_access_log_opened ON proc.bp_support_access_log (opened_at);
REVOKE UPDATE, DELETE, TRUNCATE ON proc.bp_support_access_log FROM PUBLIC;

CREATE OR REPLACE FUNCTION proc.bp_support_begin(p_reason text, p_tenant text DEFAULT NULL)
RETURNS bigint LANGUAGE plpgsql SECURITY DEFINER SET search_path = proc, pg_temp AS $$
DECLARE id bigint;
BEGIN
  INSERT INTO proc.bp_support_access_log (opened_by, reason, tenant_id)
       VALUES (session_user, p_reason, p_tenant) RETURNING log_id INTO id;
  PERFORM set_config('app.support_reason', p_reason, false);
  RETURN id;
END $$;
REVOKE ALL ON FUNCTION proc.bp_support_begin(text, text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION proc.bp_support_begin(text, text) TO procwise_readonly;
GRANT INSERT ON proc.bp_support_access_log TO procwise_readonly;
COMMIT;
"""


def rollbacks(views: List[str]) -> Dict[str, str]:
    r1 = [header(1, "ROLLBACK of add_label", """
-- Drops tenant_id ONLY from tables that did not have it before 2026-10-21 (the 20 already-labelled
-- tables keep theirs). DATA LOSS of the labels on those tables; row data is untouched.""")]
    labelled = _already_labelled()
    for t in owned():
        if t not in labelled:
            r1.append(f"DROP INDEX IF EXISTS proc.{ident('ix_bp', t, 'tenant')};\nALTER TABLE proc.{t} DROP COLUMN IF EXISTS tenant_id;")
        else:
            r1.append(f"DROP INDEX IF EXISTS proc.{ident('ix_bp', t, 'tenant')};   -- column kept: it existed before")
    r3 = [header(3, "ROLLBACK of not_null", "")]
    r3 += [f"ALTER TABLE proc.{t} ALTER COLUMN tenant_id DROP NOT NULL;" for t in owned()]
    r4 = [header(4, "ROLLBACK of row_level_security", "")]
    for t in owned():
        r4.append(f"DROP POLICY IF EXISTS bp_tenant_isolation ON proc.{t};\n"
                  f"DROP POLICY IF EXISTS bp_support_read ON proc.{t};\n"
                  f"ALTER TABLE proc.{t} NO FORCE ROW LEVEL SECURITY;\n"
                  f"ALTER TABLE proc.{t} DISABLE ROW LEVEL SECURITY;")
    r4 += [f"ALTER VIEW proc.{v} RESET (security_invoker);" for v in views]
    r5 = header(5, "ROLLBACK of support_access", "-- Run AFTER 4_row_level_security_rollback.sql. DELETES the support access log: export it first if it matters.") + """
BEGIN;
REVOKE EXECUTE ON FUNCTION proc.bp_support_begin(text, text) FROM procwise_readonly;
DROP FUNCTION IF EXISTS proc.bp_support_begin(text, text);
DROP TABLE IF EXISTS proc.bp_support_access_log;
COMMIT;
"""
    withdefault = _read_lines(_snap("proc_tables_label_default_2026-10-21.txt"))
    r6 = [header(6, "ROLLBACK of stamp_on_insert", f"-- Removes the trigger and restores the old DEFAULT '{LABEL}' on the {len(withdefault)} tables that had it.")]
    for t in owned():
        restore = f"ALTER TABLE proc.{t} ALTER COLUMN tenant_id SET DEFAULT '{LABEL}';\n" if t in withdefault else ""
        r6.append(f"BEGIN;\nDROP TRIGGER IF EXISTS tr_bp_stamp_tenant ON proc.{t};\n{restore}COMMIT;")
    r6.append("DROP FUNCTION IF EXISTS proc.bp_stamp_tenant();")
    return {"6_stamp_on_insert_rollback.sql": "\n".join(r6) + "\n", "5_support_access_rollback.sql": r5, "1_add_label_rollback.sql": "\n".join(r1) + "\n", "3_not_null_rollback.sql": "\n".join(r3) + "\n",
            "4_row_level_security_rollback.sql": "\n".join(r4) + "\n"}


def _read_lines(path: str) -> List[str]:
    with open(path) as fh:
        return [l.strip() for l in fh if l.strip()]


def _snap(name: str) -> str:
    return os.path.join(os.path.dirname(__file__), "..", "..", "tests", "tenancy", name)


def _already_labelled() -> set:
    return set(_read_lines(_snap("proc_tables_already_labelled_2026-10-21.txt")))


def files() -> Dict[str, str]:
    snap = os.path.join(os.path.dirname(__file__), "..", "..", "tests", "tenancy")
    check_classification(_read_lines(os.path.join(snap, "proc_tables_2026-10-21.txt")))
    views = _read_lines(os.path.join(snap, "proc_views_2026-10-21.txt"))
    out = {"1_add_label.sql": p1_add_label(), "2_backfill_and_index.sql": p2_backfill(),
           "3_not_null.sql": p3_not_null(), "4_row_level_security.sql": p4_rls(views),
           "5_support_access.sql": p5_support_log(), "6_stamp_on_insert.sql": p6_stamp()}
    out.update(rollbacks(views))
    return {f"{DATE}_tenant_isolation_{k}": v for k, v in out.items()}


def main(argv: List[str]) -> int:
    want = files()
    if "--check" in argv:
        stale = [n for n, body in want.items()
                 if not os.path.exists(os.path.join(OUT, n)) or open(os.path.join(OUT, n)).read() != body]
        print("stale: " + ", ".join(stale) if stale else "up to date")
        return 1 if stale else 0
    os.makedirs(OUT, exist_ok=True)
    for n, body in want.items():
        with open(os.path.join(OUT, n), "w") as fh:
            fh.write(body)
    print(f"wrote {len(want)} files to deploy/sql/tenancy ({len(OWNED)} owned tables)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
